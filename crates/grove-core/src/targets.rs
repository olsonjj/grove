//! App detection: which editors and terminals (later custom commands) Grove can open a
//! worktree in.

use std::path::{Path, PathBuf};
use std::process::Command;
use std::time::Duration;

use crate::env::{ShellEnv, resolved_env};
use crate::process;
use crate::settings::Settings;

const SPOTLIGHT_TIMEOUT: Duration = Duration::from_secs(2);
const BUNDLE_ID_ATTR: &str = "kMDItemCFBundleIdentifier";

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Editor {
    VsCode,
    Cursor,
    Zed,
    IntelliJ,
    Sublime,
}

impl Editor {
    /// Detection order; the first one found is the default until the user picks one.
    pub const ALL: [Editor; 5] = [
        Editor::VsCode,
        Editor::Cursor,
        Editor::Zed,
        Editor::IntelliJ,
        Editor::Sublime,
    ];

    /// Stable key stored in settings.
    pub fn id(self) -> &'static str {
        match self {
            Editor::VsCode => "vscode",
            Editor::Cursor => "cursor",
            Editor::Zed => "zed",
            Editor::IntelliJ => "intellij",
            Editor::Sublime => "sublime",
        }
    }

    pub fn from_id(id: &str) -> Option<Self> {
        Self::ALL.into_iter().find(|e| e.id() == id)
    }

    pub fn name(self) -> &'static str {
        match self {
            Editor::VsCode => "VS Code",
            Editor::Cursor => "Cursor",
            Editor::Zed => "Zed",
            Editor::IntelliJ => "IntelliJ IDEA",
            Editor::Sublime => "Sublime Text",
        }
    }

    fn bundle_ids(self) -> &'static [&'static str] {
        match self {
            Editor::VsCode => &["com.microsoft.VSCode"],
            Editor::Cursor => &["com.todesktop.230313mzl4w4u92"],
            Editor::Zed => &["dev.zed.Zed", "dev.zed.Zed-Preview"],
            Editor::IntelliJ => &["com.jetbrains.intellij", "com.jetbrains.intellij.ce"],
            Editor::Sublime => &["com.sublimetext.4", "com.sublimetext.3"],
        }
    }

    fn app_names(self) -> &'static [&'static str] {
        match self {
            Editor::VsCode => &["Visual Studio Code.app"],
            Editor::Cursor => &["Cursor.app"],
            Editor::Zed => &["Zed.app", "Zed Preview.app"],
            Editor::IntelliJ => &[
                "IntelliJ IDEA.app",
                "IntelliJ IDEA Ultimate.app",
                "IntelliJ IDEA CE.app",
                "IntelliJ IDEA Community Edition.app",
            ],
            Editor::Sublime => &["Sublime Text.app"],
        }
    }

    pub fn cli_name(self) -> &'static str {
        match self {
            Editor::VsCode => "code",
            Editor::Cursor => "cursor",
            Editor::Zed => "zed",
            Editor::IntelliJ => "idea",
            Editor::Sublime => "subl",
        }
    }

    /// The CLI shipped inside the app bundle, used when it isn't on PATH. IntelliJ has
    /// none: its `idea` launcher is generated by Toolbox / "Create Command-line Launcher".
    fn bundled_cli(self) -> Option<&'static str> {
        match self {
            Editor::VsCode => Some("Contents/Resources/app/bin/code"),
            Editor::Cursor => Some("Contents/Resources/app/bin/cursor"),
            Editor::Zed => Some("Contents/MacOS/cli"),
            Editor::IntelliJ => None,
            Editor::Sublime => Some("Contents/SharedSupport/bin/subl"),
        }
    }

    /// CLI flags that force a new window even when the folder is already open.
    /// IntelliJ has no such flag; it focuses an already-open project.
    pub(crate) fn new_window_args(self) -> &'static [&'static str] {
        match self {
            Editor::VsCode | Editor::Cursor | Editor::Sublime => &["--new-window"],
            Editor::Zed => &["--new"],
            Editor::IntelliJ => &[],
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Terminal {
    Terminal,
    ITerm2,
    Warp,
    Ghostty,
    Kitty,
}

impl Terminal {
    /// Detection order; Terminal.app ships with macOS, so it's the usual default.
    pub const ALL: [Terminal; 5] = [
        Terminal::Terminal,
        Terminal::ITerm2,
        Terminal::Warp,
        Terminal::Ghostty,
        Terminal::Kitty,
    ];

    pub fn id(self) -> &'static str {
        match self {
            Terminal::Terminal => "terminal",
            Terminal::ITerm2 => "iterm2",
            Terminal::Warp => "warp",
            Terminal::Ghostty => "ghostty",
            Terminal::Kitty => "kitty",
        }
    }

    pub fn from_id(id: &str) -> Option<Self> {
        Self::ALL.into_iter().find(|t| t.id() == id)
    }

    pub fn name(self) -> &'static str {
        match self {
            Terminal::Terminal => "Terminal",
            Terminal::ITerm2 => "iTerm2",
            Terminal::Warp => "Warp",
            Terminal::Ghostty => "Ghostty",
            Terminal::Kitty => "Kitty",
        }
    }

    fn bundle_ids(self) -> &'static [&'static str] {
        match self {
            Terminal::Terminal => &["com.apple.Terminal"],
            Terminal::ITerm2 => &["com.googlecode.iterm2"],
            Terminal::Warp => &["dev.warp.Warp-Stable"],
            Terminal::Ghostty => &["com.mitchellh.ghostty"],
            Terminal::Kitty => &["net.kovidgoyal.kitty"],
        }
    }

    fn app_names(self) -> &'static [&'static str] {
        match self {
            Terminal::Terminal => &["Terminal.app"],
            Terminal::ITerm2 => &["iTerm.app"],
            Terminal::Warp => &["Warp.app"],
            Terminal::Ghostty => &["Ghostty.app"],
            Terminal::Kitty => &["kitty.app"],
        }
    }

    fn cli_name(self) -> Option<&'static str> {
        match self {
            Terminal::Ghostty => Some("ghostty"),
            Terminal::Kitty => Some("kitty"),
            _ => None,
        }
    }

    fn bundled_cli(self) -> Option<&'static str> {
        match self {
            Terminal::Ghostty => Some("Contents/MacOS/ghostty"),
            Terminal::Kitty => Some("Contents/MacOS/kitty"),
            _ => None,
        }
    }
}

/// What an open target is for: Enter opens the editor, ⌘Enter the terminal.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Role {
    Editor,
    Terminal,
}

impl Role {
    fn noun(self) -> &'static str {
        match self {
            Role::Editor => "editor",
            Role::Terminal => "terminal",
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum TargetKind {
    Editor(Editor),
    Terminal(Terminal),
}

impl TargetKind {
    /// Every detectable kind, editors then terminals, each in its detection order.
    pub fn all() -> impl Iterator<Item = TargetKind> {
        Editor::ALL
            .into_iter()
            .map(TargetKind::Editor)
            .chain(Terminal::ALL.into_iter().map(TargetKind::Terminal))
    }

    pub fn role(self) -> Role {
        match self {
            TargetKind::Editor(_) => Role::Editor,
            TargetKind::Terminal(_) => Role::Terminal,
        }
    }

    pub fn id(self) -> &'static str {
        match self {
            TargetKind::Editor(e) => e.id(),
            TargetKind::Terminal(t) => t.id(),
        }
    }

    pub fn name(self) -> &'static str {
        match self {
            TargetKind::Editor(e) => e.name(),
            TargetKind::Terminal(t) => t.name(),
        }
    }

    fn from_id(role: Role, id: &str) -> Option<Self> {
        match role {
            Role::Editor => Editor::from_id(id).map(TargetKind::Editor),
            Role::Terminal => Terminal::from_id(id).map(TargetKind::Terminal),
        }
    }

    fn bundle_ids(self) -> &'static [&'static str] {
        match self {
            TargetKind::Editor(e) => e.bundle_ids(),
            TargetKind::Terminal(t) => t.bundle_ids(),
        }
    }

    fn app_names(self) -> &'static [&'static str] {
        match self {
            TargetKind::Editor(e) => e.app_names(),
            TargetKind::Terminal(t) => t.app_names(),
        }
    }

    fn cli_name(self) -> Option<&'static str> {
        match self {
            TargetKind::Editor(e) => Some(e.cli_name()),
            TargetKind::Terminal(t) => t.cli_name(),
        }
    }

    fn bundled_cli(self) -> Option<&'static str> {
        match self {
            TargetKind::Editor(e) => e.bundled_cli(),
            TargetKind::Terminal(t) => t.bundled_cli(),
        }
    }
}

/// Something Grove can launch on a worktree.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct OpenTarget {
    pub kind: TargetKind,
    /// The `.app` bundle, if found.
    pub app: Option<PathBuf>,
    /// CLI on the resolved PATH, else the one inside the app bundle.
    pub cli: Option<PathBuf>,
}

impl OpenTarget {
    pub fn id(&self) -> &str {
        self.kind.id()
    }

    pub fn name(&self) -> &str {
        self.kind.name()
    }

    pub fn role(&self) -> Role {
        self.kind.role()
    }
}

/// Installed editors and terminals, in `TargetKind::all` order. Blocking (Spotlight +
/// filesystem); run off the UI thread.
pub fn detect() -> Vec<OpenTarget> {
    let home = crate::tree::home_dir();
    let mut dirs = vec![PathBuf::from("/Applications")];
    if let Some(home) = home {
        dirs.push(home.join("Applications"));
    }
    dirs.extend(
        [
            "/Applications/Setapp",
            "/Applications/Utilities",
            "/System/Applications/Utilities",
        ]
        .map(PathBuf::from),
    );
    detect_in(resolved_env(), &dirs, true)
}

/// `detect` with explicit app folders and PATH; `spotlight` adds apps found by bundle id
/// anywhere else.
pub fn detect_in(env: &ShellEnv, app_dirs: &[PathBuf], spotlight: bool) -> Vec<OpenTarget> {
    let found = if spotlight {
        spotlight_apps()
    } else {
        Vec::new()
    };
    TargetKind::all()
        .filter_map(|kind| {
            let app = app_dirs
                .iter()
                .flat_map(|dir| kind.app_names().iter().map(move |n| dir.join(n)))
                .find(|p| p.is_dir())
                .or_else(|| {
                    found
                        .iter()
                        .find(|(_, id)| kind.bundle_ids().contains(&id.as_str()))
                        .map(|(p, _)| p.clone())
                });
            let cli = kind
                .cli_name()
                .and_then(|name| env.which(name))
                .or_else(|| {
                    let rel = kind.bundled_cli()?;
                    app.as_ref().map(|a| a.join(rel)).filter(|p| p.is_file())
                });
            (app.is_some() || cli.is_some()).then_some(OpenTarget { kind, app, cli })
        })
        .collect()
}

/// `(app path, bundle id)` for every known bundle Spotlight indexes.
fn spotlight_apps() -> Vec<(PathBuf, String)> {
    let query = TargetKind::all()
        .flat_map(|k| k.bundle_ids())
        .map(|id| format!("{BUNDLE_ID_ATTR} == '{id}'"))
        .collect::<Vec<_>>()
        .join(" || ");
    let mut cmd = Command::new("/usr/bin/mdfind");
    cmd.args(["-attr", BUNDLE_ID_ATTR, &query]);
    match process::run(cmd, SPOTLIGHT_TIMEOUT) {
        Ok(out) if out.status.success() => parse_mdfind(&out.stdout),
        _ => Vec::new(),
    }
}

fn parse_mdfind(out: &str) -> Vec<(PathBuf, String)> {
    let marker = format!("{BUNDLE_ID_ATTR} = ");
    out.lines()
        .filter_map(|line| {
            let (path, id) = line.rsplit_once(&marker)?;
            let path = Path::new(path.trim_end());
            let skip = path.components().any(|c| c.as_os_str() == ".Trash");
            (!skip && path.is_dir()).then(|| (path.to_path_buf(), id.trim().to_string()))
        })
        .collect()
}

/// Why there's no editor or terminal to open with.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum NoTarget {
    /// The configured default names an app that is no longer installed.
    Uninstalled(Role, String),
    NoneDetected(Role),
}

impl std::fmt::Display for NoTarget {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            NoTarget::Uninstalled(role, id) => {
                let name: &str = TargetKind::from_id(*role, id).map_or(id, |k| k.name());
                let noun = role.noun();
                write!(f, "Your default {noun}, {name}, isn't installed anymore")
            }
            NoTarget::NoneDetected(role) => {
                let names: Vec<&str> = TargetKind::all()
                    .filter(|k| k.role() == *role)
                    .map(TargetKind::name)
                    .collect();
                write!(
                    f,
                    "No {} found (looked for {})",
                    role.noun(),
                    names.join(", ")
                )
            }
        }
    }
}

/// The configured default for `role`; with none configured, the first detected one. A
/// configured app that's gone is an error, not a silent switch to another app.
pub fn default_target<'a>(
    role: Role,
    settings: &Settings,
    targets: &'a [OpenTarget],
) -> Result<&'a OpenTarget, NoTarget> {
    let configured = match role {
        Role::Editor => settings.default_editor.as_deref(),
        Role::Terminal => settings.default_terminal.as_deref(),
    };
    let mut of_role = targets.iter().filter(|t| t.role() == role);
    match configured {
        Some(id) => of_role
            .find(|t| t.id() == id)
            .ok_or_else(|| NoTarget::Uninstalled(role, id.to_string())),
        None => of_role.next().ok_or(NoTarget::NoneDetected(role)),
    }
}

pub fn default_editor<'a>(
    settings: &Settings,
    targets: &'a [OpenTarget],
) -> Result<&'a OpenTarget, NoTarget> {
    default_target(Role::Editor, settings, targets)
}

pub fn default_terminal<'a>(
    settings: &Settings,
    targets: &'a [OpenTarget],
) -> Result<&'a OpenTarget, NoTarget> {
    default_target(Role::Terminal, settings, targets)
}

#[cfg(test)]
mod tests {
    use std::fs;

    use super::*;
    use crate::env::PathSource;

    fn env(path: &Path) -> ShellEnv {
        ShellEnv {
            path: path.display().to_string(),
            source: PathSource::LoginShell,
            shell: "/bin/zsh".into(),
        }
    }

    fn executable(path: &Path) {
        use std::os::unix::fs::PermissionsExt;
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        fs::write(path, "#!/bin/sh\n").unwrap();
        fs::set_permissions(path, fs::Permissions::from_mode(0o755)).unwrap();
    }

    fn ids(targets: &[OpenTarget]) -> Vec<&str> {
        targets.iter().map(OpenTarget::id).collect()
    }

    #[test]
    fn detects_by_app_bundle_and_cli() {
        let tmp = tempfile::TempDir::new().unwrap();
        let apps = tmp.path().join("Applications");
        let bin = tmp.path().join("bin");
        fs::create_dir_all(&bin).unwrap();
        // Zed: app only, CLI from the bundle. VS Code: app plus CLI on PATH.
        // Sublime: CLI only. IntelliJ: app, no CLI anywhere. Cursor: absent.
        executable(&apps.join("Zed.app/Contents/MacOS/cli"));
        fs::create_dir_all(apps.join("Visual Studio Code.app")).unwrap();
        executable(&bin.join("code"));
        executable(&bin.join("subl"));
        fs::create_dir_all(apps.join("IntelliJ IDEA CE.app")).unwrap();

        let t = detect_in(&env(&bin), std::slice::from_ref(&apps), false);
        assert_eq!(ids(&t), ["vscode", "zed", "intellij", "sublime"]);
        assert_eq!(t[0].cli, Some(bin.join("code")));
        assert_eq!(t[0].app, Some(apps.join("Visual Studio Code.app")));
        assert_eq!(t[1].cli, Some(apps.join("Zed.app/Contents/MacOS/cli")));
        assert_eq!(t[2].cli, None);
        assert_eq!(t[3].app, None);
    }

    #[test]
    fn nothing_installed() {
        let tmp = tempfile::TempDir::new().unwrap();
        assert!(detect_in(&env(tmp.path()), &[tmp.path().into()], false).is_empty());
    }

    #[test]
    fn parses_spotlight_output() {
        let tmp = tempfile::TempDir::new().unwrap();
        let app = tmp.path().join("My Apps/Visual Studio Code.app");
        fs::create_dir_all(&app).unwrap();
        let out = format!(
            "{}   kMDItemCFBundleIdentifier = com.microsoft.VSCode\n/gone/Zed.app   kMDItemCFBundleIdentifier = dev.zed.Zed\n",
            app.display()
        );
        assert_eq!(
            parse_mdfind(&out),
            [(app, "com.microsoft.VSCode".to_string())]
        );
    }

    fn target(e: Editor) -> OpenTarget {
        OpenTarget {
            kind: TargetKind::Editor(e),
            app: None,
            cli: Some(e.cli_name().into()),
        }
    }

    #[test]
    fn default_editor_prefers_settings_then_first_detected() {
        let targets = [target(Editor::Zed), target(Editor::Sublime)];
        let mut s = Settings::default();
        assert_eq!(default_editor(&s, &targets).unwrap().id(), "zed");
        s.default_editor = Some("sublime".into());
        assert_eq!(default_editor(&s, &targets).unwrap().id(), "sublime");
        s.default_editor = Some("vscode".into());
        let err = default_editor(&s, &targets).unwrap_err();
        assert_eq!(err, NoTarget::Uninstalled(Role::Editor, "vscode".into()));
        assert_eq!(
            err.to_string(),
            "Your default editor, VS Code, isn't installed anymore"
        );
        assert_eq!(
            default_editor(&Settings::default(), &[]).unwrap_err(),
            NoTarget::NoneDetected(Role::Editor)
        );
    }

    #[test]
    fn detects_terminals() {
        let tmp = tempfile::TempDir::new().unwrap();
        let apps = tmp.path().join("Applications");
        let utils = tmp.path().join("System/Applications/Utilities");
        let bin = tmp.path().join("bin");
        fs::create_dir_all(&bin).unwrap();
        // Terminal in Utilities, Warp app only, Ghostty with bundled CLI, kitty CLI only.
        fs::create_dir_all(utils.join("Terminal.app")).unwrap();
        fs::create_dir_all(apps.join("Warp.app")).unwrap();
        executable(&apps.join("Ghostty.app/Contents/MacOS/ghostty"));
        executable(&bin.join("kitty"));

        let t = detect_in(&env(&bin), &[apps.clone(), utils.clone()], false);
        assert_eq!(ids(&t), ["terminal", "warp", "ghostty", "kitty"]);
        assert!(t.iter().all(|t| t.role() == Role::Terminal));
        assert_eq!(t[0].app, Some(utils.join("Terminal.app")));
        assert_eq!(t[0].cli, None);
        assert_eq!(
            t[2].cli,
            Some(apps.join("Ghostty.app/Contents/MacOS/ghostty"))
        );
        assert_eq!(
            (t[3].app.clone(), t[3].cli.clone()),
            (None, Some(bin.join("kitty")))
        );
    }

    #[test]
    fn default_terminal_prefers_settings_then_first_detected() {
        let t = |k: Terminal| OpenTarget {
            kind: TargetKind::Terminal(k),
            app: None,
            cli: None,
        };
        let targets = [
            target(Editor::Zed),
            t(Terminal::Terminal),
            t(Terminal::Warp),
        ];
        let mut s = Settings::default();
        assert_eq!(default_terminal(&s, &targets).unwrap().id(), "terminal");
        assert_eq!(default_editor(&s, &targets).unwrap().id(), "zed");
        s.default_terminal = Some("warp".into());
        assert_eq!(default_terminal(&s, &targets).unwrap().id(), "warp");
        s.default_terminal = Some("iterm2".into());
        assert_eq!(
            default_terminal(&s, &targets).unwrap_err().to_string(),
            "Your default terminal, iTerm2, isn't installed anymore"
        );
        assert_eq!(
            default_terminal(&Settings::default(), &targets[..1])
                .unwrap_err()
                .to_string(),
            "No terminal found (looked for Terminal, iTerm2, Warp, Ghostty, Kitty)"
        );
    }
}
